export function getClipartByCategory(category: string): ClipartItem[] {
  return clipartLibrary.filter(
    (item) => item.category.toLowerCase() === category.toLowerCase()
  );
}

export function getAllClipartCategories(): string[] {
  return [...new Set(clipartLibrary.map((item) => item.category))];
}

export function searchClipart(query: string): ClipartItem[] {
  const q = query.toLowerCase().trim();
  if (!q) return clipartLibrary;
  return clipartLibrary.filter(
    (item) =>
      item.name.toLowerCase().includes(q) ||
      item.category.toLowerCase().includes(q) ||
      item.tags.some((t) => t.toLowerCase().includes(q))
  );
}
